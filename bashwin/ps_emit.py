_TEST_OPS = frozenset(('-eq', '-ne', '-lt', '-le', '-gt', '-ge', '-z', '-n', '-f', '-d', '-e',
                       '-s', '-r', '-w', '-a', '-o'))
_COND_FILE = frozenset(('-e', '-a', '-f', '-d', '-s', '-r', '-w'))
