_PARAM_OPS = frozenset((':-', '-', ':+', '+', ':=', '=', ':?', '?'))
_IDENT = re.compile(r'[A-Za-z_][A-Za-z0-9_]*\Z')
_BRACE = re.compile(r'\{[^{}]*(,|\.\.)[^{}]*\}')
_ATOK = re.compile(r'\s*(?:(0[xX][0-9a-fA-F]+|[0-9]+)|([A-Za-z_][A-Za-z0-9_]*)|\x01([0-9]+)\x01'
                   r'|(\|\||&&|==|!=|<=|>=|\+\+|--|\+=|-=|\*=|/=|%=|&=|\|=|[-+*/%()<>=!&|]))')
_ASSIGN_OPS = frozenset(('=', '+=', '-=', '*=', '/=', '%=', '&=', '|='))
_LEVELS = (('||',), ('&&',), ('|',), ('&',), ('==', '!='), ('<', '<=', '>', '>='), ('+', '-'),
           ('*', '/', '%'))
_CMP = {'==': '-eq', '!=': '-ne', '<': '-lt', '<=': '-le', '>': '-gt', '>=': '-ge'}


# ---------------------------------------------------------------- PowerShell の文字列リテラル
def sq(text):
    """印字可能な ASCII だけの文字列を単一引用符リテラルにする。"""
    return "'" + text.replace("'", "''") + "'"


def _plain(text):
    return all(' ' <= c <= '~' for c in text)


def _dq_escape(text):
    out = []
    for c in text:
        o = ord(c)
        if c == '`':
            out.append('``')
        elif c == '"':
            out.append('`"')
        elif c == '$':
            out.append('`$')
        elif c == '\n':
            out.append('`n')
        elif c == '\r':
            out.append('`r')
        elif c == '\t':
            out.append('`t')
        elif c == '\0':
            out.append('`0')
        elif 0x20 <= o <= 0x7E:
            out.append(c)
        elif 0xDC80 <= o <= 0xDCFF:
            raise ValueError('invalid UTF-8 byte in a literal')
        elif o > 0xFFFF:
            o -= 0x10000
            out.append('$([char]%d)$([char]%d)' % (0xD800 + (o >> 10), 0xDC00 + (o & 0x3FF)))
        else:
            out.append('$([char]%d)' % o)
    return ''.join(out)


def _ascii(text):
    return ''.join(c if ' ' <= c <= '~' else (' ' if c == '\t' else '\\u%04x' % ord(c))
                   for c in text)


def _gq(text):
    """パターン中で文字どおりに扱う部分(引用された部分)をグロブ用にエスケープする。"""
    return re.sub(r'([\\*?\[\]])', r'\\\1', text)


def _has_glob(t):
    if '*' in t or '?' in t:
        return True
    k = t.find('[')
    return k >= 0 and ']' in t[k + 1:]


def _paren(e):
    return e if e.startswith('(') else '(' + e + ')'


class _AErr(Exception):
    pass


class _AParser(object):
    """算術式(演算子は + - * / % 比較 論理 ビット& | 代入 ++ --)を PowerShell の式にする。"""

    def __init__(self, toks):
        self.t = toks
        self.i = 0

    def peek(self):
        return self.t[self.i] if self.i < len(self.t) else ('end', None)

    def eat(self, *ops):
        k, v = self.peek()
        if k == 'op' and v in ops:
            self.i += 1
            return v
        return None

    def parse(self):
        e = self.assign()
        if self.i != len(self.t):
            raise _AErr('unexpected `%s`' % (self.peek()[1],))
        return e

    def assign(self):
        k, v = self.peek()
        if k == 'id' and self.i + 1 < len(self.t) and self.t[self.i + 1][0] == 'op' \
                and self.t[self.i + 1][1] in _ASSIGN_OPS:
            op = self.t[self.i + 1][1]
            self.i += 2
            rhs = self.assign()
            if op != '=':
                rhs = self.binop(op[:-1], '(__vn %s)' % sq(v), rhs)
            return '(__aset %s %s)' % (sq(v), _paren(rhs))
        return self.level(0)

    def level(self, k):
        if k == len(_LEVELS):
            return self.unary()
        e = self.level(k + 1)
        while True:
            op = self.eat(*_LEVELS[k])
            if op is None:
                return e
            e = self.binop(op, e, self.level(k + 1))

    @staticmethod
    def binop(op, a, b):
        if op in ('+', '-', '*'):
            return '(%s %s %s)' % (a, op, b)
        if op == '/':
            return '(__div %s %s)' % (_paren(a), _paren(b))
        if op == '%':
            return '(__mod %s %s)' % (_paren(a), _paren(b))
        if op in _CMP:
            return '([long](%s %s %s))' % (a, _CMP[op], b)
        if op == '&&':
            return '([long]((%s -ne 0) -and (%s -ne 0)))' % (a, b)
        if op == '||':
            return '([long]((%s -ne 0) -or (%s -ne 0)))' % (a, b)
        if op == '&':
            return '(%s -band %s)' % (a, b)
        return '(%s -bor %s)' % (a, b)

    def unary(self):
        op = self.eat('!', '-', '+', '++', '--')
        if op == '!':
            return '([long](%s -eq 0))' % self.unary()
        if op == '-':
            return '(-%s)' % _paren(self.unary())
        if op == '+':
            return self.unary()
        if op in ('++', '--'):
            k, v = self.peek()
            if k != 'id':
                raise _AErr('%s needs a variable' % op)
            self.i += 1
            return '(__ainc %s (%s) $false)' % (sq(v), '1L' if op == '++' else '-1L')
        return self.primary()

    def primary(self):
        k, v = self.peek()
        if k == 'num':
            self.i += 1
            return '%dL' % v
        if k == 'ph':
            self.i += 1
            return '(__si %s)' % v
        if k == 'id':
            self.i += 1
            op = self.eat('++', '--')
            if op:
                return '(__ainc %s (%s) $true)' % (sq(v), '1L' if op == '++' else '-1L')
            return '(__vn %s)' % sq(v)
        if self.eat('('):
            e = self.assign()
            if not self.eat(')'):
                raise _AErr('missing )')
            return _paren(e)
        raise _AErr('operand expected' if k == 'end' else 'unexpected `%s`' % (v,))


class Emitter(object):
    def __init__(self, src, tools='block'):
        from . import applets, shbuiltins
        self.src_lines = src.replace('\r\n', '\n').split('\n')
        self.tools = tools
        self.unix_tools = frozenset(applets.REGISTRY)
        self.shell_builtins = frozenset(shbuiltins.BUILTINS) | _BASH_BUILTINS
        self.funcs = set()
        self.use_e = False
        self.use_u = False
        self._reset()

    def _reset(self):
        self.problems = []      # [(line, category, message)]
        self.line = 0
        self.lines = []
        self.ind = 1
        self.tmp = 0
        self.loops = []         # [(label, status_var)] 今いる関数の中のループ
        self.func_depth = 0
        self.in_cs = 0
        self.last_comment = 0

    def run(self, tree):
        self.node(tree)         # 1 回目: 関数名と set -e/-u の使用を集める
        self._reset()
        self.node(tree)         # 2 回目: 生成
        return self.lines

    # ---- 出力の小道具
    def w(self, text):
        self.lines.append('    ' * self.ind + text)

    def bad(self, category, msg):
        self.problems.append((self.line, category, msg))

    def new(self, prefix):
        self.tmp += 1
        return '$__%s%d' % (prefix, self.tmp)

    def comment(self, line):
        if self.in_cs or not line or line == self.last_comment or line > len(self.src_lines):
            return
        self.last_comment = line
        text = self.src_lines[line - 1].strip()
        if text:
            self.w('# %d: %s' % (line, _ascii(text)))

    def ck(self):
        if self.use_e and not self.in_cs:
            self.w('__ck')

    def cd_enter(self):
        """-e を無視する文脈(条件部、&& || の左辺、! の対象)に入る。"""
        if not self.use_e or self.in_cs:
            return None
        v = self.new('k')
        self.w('%s = $script:__cd; $script:__cd = %s + 1' % (v, v))
        return v

    def cd_leave(self, v):
        if v:
            self.w('$script:__cd = %s' % v)

    def lit(self, text):
        if _plain(text):
            return sq(text)
        try:
            return '"' + _dq_escape(text) + '"'
        except ValueError as e:
            self.bad('encoding', str(e))
            return "''"

    def render(self, segs):
        merged = []
        for kind, v in segs:
            if kind == 'l' and merged and merged[-1][0] == 'l':
                merged[-1] = ('l', merged[-1][1] + v)
            elif kind != 'l' or v:
                merged.append((kind, v))
        if not merged:
            return "''"
        if len(merged) == 1 and merged[0][0] == 'l':
            return self.lit(merged[0][1])
        out = ['"']
        try:
            for kind, v in merged:
                out.append(_dq_escape(v) if kind == 'l' else '$(' + v + ')')
        except ValueError as e:
            self.bad('encoding', str(e))
            return "''"
        out.append('"')
        return ''.join(out)

    # ---- 語
    @staticmethod
    def _lit(w):
        """語が完全に静的ならその文字列、そうでなければ None。"""
        if w is None:
            return None
        out = []
        for p in w.parts:
            tp = type(p)
            if tp in (Lit, Esc, SQ):
                out.append(p.text)
            elif tp is DQ and all(type(q) is Lit for q in p.parts):
                out.extend(q.text for q in p.parts)
            else:
                return None
        return ''.join(out)

    @staticmethod
    def _is_at(w):
        if len(w.parts) != 1 or type(w.parts[0]) is not DQ or len(w.parts[0].parts) != 1:
            return False
        p = w.parts[0].parts[0]
        return type(p) is Param and p.name == '@' and p.op is None and p.index is None \
            and not p.length and not p.indirect

    def has_cmdsub(self, w):
        def scan(parts):
            for p in parts:
                tp = type(p)
                if tp is CmdSub:
                    return True
                if tp is DQ and scan(p.parts):
                    return True
                if tp is Param and p.arg is not None and scan(p.arg.parts):
                    return True
            return False
        return scan(w.parts)

    def wstr(self, w, ctx):
        """1 つの文字列になる語を PowerShell の文字列式(1 トークン)にする。
        ctx: arg(コマンド引数) / assign / redir / case / cond"""
        segs = []
        self.segs(w.parts, ctx, False, segs, True)
        return self.render(segs)

    def segs(self, parts, ctx, quoted, out, first=False):
        for i, p in enumerate(parts):
            tp = type(p)
            if tp is Lit:
                t = p.text
                if not quoted:
                    if first and i == 0 and t.startswith('~'):
                        if t == '~' or t.startswith('~/'):
                            out.append(('e', self.getter('HOME')))
                            t = t[1:]
                        else:
                            self.bad('tilde', 'tilde expansion of a user name (~user)')
                    if ctx in ('arg', 'redir') and _has_glob(t):
                        self.bad('glob', 'pathname expansion (unquoted * ? [ ])')
                    if ctx == 'arg' and _BRACE.search(t):
                        self.bad('brace', 'brace expansion')
                out.append(('l', t))
            elif tp is Esc or tp is SQ:
                out.append(('l', p.text))
            elif tp is DQ:
                self.segs(p.parts, ctx, True, out)
            elif tp is Param:
                out.append(('e', self.param(p, quoted or ctx != 'arg')))
            elif tp is CmdSub:
                if not quoted and ctx == 'arg':
                    self.bad('unquoted', 'unquoted command substitution (word splitting)')
                out.append(('e', self.cmdsub(p)))
            elif tp is Arith:
                out.append(('e', self.arith(p.word)))
            elif tp is ProcSub:
                self.bad('procsub', 'process substitution')
            else:
                self.bad('word', 'unsupported word part %s' % tp.__name__)

    def wargs(self, words):
        """語の並びを PowerShell の文字列配列の式にする("$@" だけは複数要素に展開する)。"""
        groups = []
        cur = []
        for w in words:
            if self._is_at(w):
                if cur:
                    groups.append('@(%s)' % ', '.join(cur))
                    cur = []
                groups.append('$__P')
            else:
                cur.append(self.wstr(w, 'arg'))
        if cur or not groups:
            groups.append('@(%s)' % ', '.join(cur))
        if len(groups) == 1:
            return groups[0]
        return '(' + ' + '.join(groups) + ')'

    def wpat(self, w):
        """パターン(case / [[ == ]] の右辺)。引用された部分は文字どおり、それ以外はグロブ。"""
        segs = []
        for p in w.parts:
            tp = type(p)
            if tp is Lit:
                segs.append(('l', p.text))
            elif tp is Esc or tp is SQ:
                segs.append(('l', _gq(p.text)))
            elif tp is DQ:
                for q in p.parts:
                    if type(q) is Lit:
                        segs.append(('l', _gq(q.text)))
                    else:
                        inner = []
                        self.segs([q], 'case', True, inner)
                        segs.append(('e', '__gq %s' % self.render(inner)))
            else:
                self.segs([p], 'case', True, segs)
        return self.render(segs)

    def getter(self, name):
        if name == '#':
            return '$__P.Length'
        if name == '?':
            return '$script:__st'
        if name.isdigit():
            return '$__0' if int(name) == 0 else '__get %s' % sq(name)
        if self.use_u:
            return '__get %s' % sq(name)
        return '$__V[%s]' % sq(name)

    def param(self, p, quoted):
        name = p.name
        if p.index is not None:
            self.bad('array', 'array element / array expansion')
            return "''"
        if p.length or p.indirect:
            self.bad('param-op', 'parameter expansion ${%s%s}' % ('#' if p.length else '!', name))
            return "''"
        if name in ('*', '!', '-', '$', '@'):
            self.bad('special-param', 'special parameter $%s (only a standalone "$@" is supported)'
                     % name)
            return "''"
        if name in _SPECIAL_VARS:
            self.bad('special-var', 'shell variable $%s is not provided by the runtime' % name)
        if not quoted and name not in ('?', '#'):   # $? と $# は数字だけなので分割されない
            self.bad('unquoted', 'unquoted expansion $%s (word splitting / globbing)' % name)
        get = self.getter(name)
        op = p.op
        if op is None:
            return get
        if op not in _PARAM_OPS:
            self.bad('param-op', 'parameter expansion operator ${%s%s...}' % (name, op))
            return get
        test = ('__nn %s' if op[0] == ':' else '__isset %s') % sq(name)
        word = self.wstr(p.arg, 'assign') if p.arg is not None else "''"
        kind = op[-1]
        if kind == '-':
            return 'if (%s) { %s } else { %s }' % (test, get, word)
        if kind == '+':
            return "if (%s) { %s } else { '' }" % (test, word)
        if kind == '=':
            if not _IDENT.match(name):
                self.bad('param-op', 'cannot assign to $%s with ${%s%s...}' % (name, name, op))
            return 'if (-not (%s)) { __set %s %s }; %s' % (test, sq(name), word, get)
        return 'if (%s) { %s } else { __perr %s %s }' % (test, get, sq(name), word)

    def cmdsub(self, p):
        saved = (self.lines, self.ind, self.loops, self.func_depth)
        self.lines, self.ind, self.loops, self.func_depth = [], 0, [], 0
        self.in_cs += 1
        self.node(p.node)
        body = self.lines
        self.in_cs -= 1
        self.lines, self.ind, self.loops, self.func_depth = saved
        if not body:
            return "''"
        if len(body) == 1 and '\n' not in body[0]:
            return '__cs { %s }' % body[0].strip()
        pad = '    ' * (self.ind + 1)
        return '__cs {\n' + '\n'.join(pad + ln for ln in body) + '\n' + '    ' * self.ind + '}'

    # ---- 算術
    def arith(self, w):
        if w is None:
            return '0L'
        text = []
        holders = []

        def collect(parts):
            for p in parts:
                tp = type(p)
                if tp is Lit:
                    text.append(p.text)
                elif tp is DQ:
                    collect(p.parts)
                elif tp is Param and p.op is None and p.index is None and not p.length \
                        and not p.indirect and (_IDENT.match(p.name) or p.name.isdigit()
                                                or p.name in ('#', '?')):
                    if p.name in _SPECIAL_VARS:
                        self.bad('special-var', 'shell variable $%s is not provided by the runtime'
                                 % p.name)
                    holders.append(self.render([('e', self.getter(p.name))]))
                    text.append('\x01%d\x01' % (len(holders) - 1))
                else:
                    raise _AErr('nested expansion inside an arithmetic expression')
        try:
            collect(w.parts)
            src = ''.join(text)
            toks = []
            pos = 0
            while pos < len(src):
                if src[pos:].strip() == '':
                    break
                m = _ATOK.match(src, pos)
                if not m:
                    raise _AErr('operator outside the supported set near `%s`'
                                % src[pos:pos + 12].strip())
                pos = m.end()
                if m.group(1) is not None:
                    t = m.group(1)
                    if t[:2] in ('0x', '0X'):
                        v = int(t, 16)
                    elif len(t) > 1 and t[0] == '0':
                        if not re.match(r'[0-7]+\Z', t):
                            raise _AErr('%s: value too great for base' % t)
                        v = int(t, 8)
                    else:
                        v = int(t)
                    if v > 0x7FFFFFFFFFFFFFFF:
                        raise _AErr('%s: integer out of the 64-bit range' % t)
                    toks.append(('num', v))
                elif m.group(2) is not None:
                    if m.group(2) in _SPECIAL_VARS:
                        self.bad('special-var', 'shell variable %s is not provided by the runtime'
                                 % m.group(2))
                    toks.append(('id', m.group(2)))
                elif m.group(3) is not None:
                    toks.append(('ph', holders[int(m.group(3))]))
                else:
                    toks.append(('op', m.group(4)))
            if not toks:
                return '0L'
            # 64bit からあふれると PowerShell は黙って double にする。[long] に戻せなければ止まる
            return '([long]%s)' % _AParser(toks).parse()
        except _AErr as e:
            self.bad('arith', 'arithmetic: %s' % e)
            return '0L'

    # ---- [[ ]]
    def cond(self, e):
        k = e[0]
        if k == 'or':
            return '(%s -or %s)' % (self.cond(e[1]), self.cond(e[2]))
        if k == 'and':
            return '(%s -and %s)' % (self.cond(e[1]), self.cond(e[2]))
        if k == 'not':
            return '(-not %s)' % self.cond(e[1])
        if k == 'word':
            return '((%s).Length -gt 0)' % self.wstr(e[1], 'cond')
        if k == 'unary':
            op = e[1]
            s = self.wstr(e[2], 'cond')
            if op == '-z':
                return '((%s).Length -eq 0)' % s
            if op == '-n':
                return '((%s).Length -gt 0)' % s
            if op in _COND_FILE:
                return '(__tunary %s %s)' % (sq(op), s)
            self.bad('test-op', '[[ %s ]]' % op)
            return '$false'
        op = e[1]
        a = self.wstr(e[2], 'cond')
        if op in ('==', '='):
            return '(__m %s %s)' % (a, self.wpat(e[3]))
        if op == '!=':
            return '(-not (__m %s %s))' % (a, self.wpat(e[3]))
        if op == '=~':
            self.bad('regex', '[[ =~ ]] regular expression match')
            return '$false'
        b = self.wstr(e[3], 'cond')
        if op in ('<', '>'):
            return '([string]::CompareOrdinal(%s, %s) -%s 0)' % (a, b, 'lt' if op == '<' else 'gt')
        if op in _COND_NUM:
            return '((__num %s 0) %s (__num %s 0))' % (a, op, b)
        self.bad('test-op', '[[ %s ]]' % op)
        return '$false'

    # ---- リダイレクト
    def rspec(self, redirs):
        spec = []
        for r in redirs or ():
            op = r.op
            if op in ('<<', '<<-', '<<<'):
                self.bad('heredoc', 'here-document / here-string')
                continue
            if op in ('<', '<>', '<&'):
                self.bad('stdin-redirect', 'input redirection')
                continue
            if op in ('&>', '&>>'):
                fd = '1'
                kind = 'b' if op == '&>' else 'ba'
            else:
                n = 1 if r.fd is None else r.fd
                if n not in (1, 2):
                    self.bad('fd', 'file descriptor %s (only 1 and 2 are supported)' % n)
                    continue
                fd = str(n)
                if op == '>&':
                    t = self._lit(r.target)
                    if t in ('1', '2'):
                        if t != fd:
                            spec += [sq(fd), "'d'", sq(t)]
                        continue
                    if t is None or t == '-' or t.isdigit() or r.fd is not None:
                        self.bad('fd', 'file descriptor duplication other than 2>&1 / >&2')
                        continue
                    kind = 'b'          # >&file は &>file と同じ
                elif op in ('>', '>|'):
                    kind = 'w'
                elif op == '>>':
                    kind = 'a'
                else:
                    self.bad('fd', 'redirection operator %s' % op)
                    continue
            spec += [sq(fd), sq(kind), self.wstr(r.target, 'redir')]
        return spec

    def wrap(self, spec, body):
        if not spec:
            body()
            return
        self.w('if (__rpush @(%s)) {' % ', '.join(spec))
        self.ind += 1
        self.w('try {')
        self.ind += 1
        body()
        self.ind -= 1
        self.w('} finally { __rpop }')
        self.ind -= 1
        self.w('}')

    # ---- コマンド
    def node(self, n):
        self._handlers[type(n)](self, n)

    def n_list(self, n):
        for item, is_async in n.items:
            self.node(item)
            if is_async:
                self.bad('background', 'background job (&)')

    def n_andor(self, n):
        k = self.cd_enter()
        self.node(n.first)
        self.cd_leave(k)
        last = len(n.rest) - 1
        for idx, (op, pl) in enumerate(n.rest):
            self.w('if ($script:__st -%s 0) {' % ('eq' if op == '&&' else 'ne'))
            self.ind += 1
            k = self.cd_enter() if idx != last else None
            self.node(pl)
            self.cd_leave(k)
            self.ind -= 1
            self.w('}')

    def n_pipeline(self, n):
        if len(n.cmds) > 1:
            for c in n.cmds:
                self.node(c)
            self.bad('pipeline', 'pipeline (|)')
            return
        if not n.negate:
            self.node(n.cmds[0])
            return
        k = self.cd_enter()
        self.node(n.cmds[0])
        self.cd_leave(k)
        self.w('$script:__st = [int]($script:__st -eq 0)')

    def n_simple(self, n):
        self.line = n.line
        self.comment(n.line)
        spec = self.rspec(n.redirs)
        if not n.words:
            self.wrap(spec, lambda: self.assignments(n))
            self.ck()
            return
        if n.assigns:
            self.bad('tmpenv', 'temporary environment assignment before a command')
        name = self._lit(n.words[0])
        res = []
        self.wrap(spec, lambda: res.append(self.command(n, name)))
        if res[0] or spec:
            self.ck()

    def assignments(self, n):
        has_cs = False
        for name, idx, append, value in n.assigns:
            if idx is not None or type(value) is ArrayLit:
                self.bad('array', 'array assignment')
                continue
            if append:
                self.bad('append', 'append assignment +=')
                continue
            if self.has_cmdsub(value):
                has_cs = True
            self.w('__set %s %s' % (sq(name), self.wstr(value, 'assign')))
        if not has_cs:
            self.w('$script:__st = 0')

    def command(self, n, name):
        """単純コマンドを 1 つ出力する。戻り値は「実行後に -e の判定をするか」。"""
        words = n.words
        args = words[1:]
        if name is None or name in self.funcs:
            self.w('__run %s' % self.wargs(words))
            return True
        if name in ('break', 'continue'):
            return self.c_loopctl(name, args)
        if name == 'return':
            if self.func_depth == 0:
                self.bad('return', '`return` outside of a function body')
            if len(args) > 1:
                self.bad('return', '`return` with more than one argument')
            if args:
                t = self._lit(args[0])
                if t is not None and t.isdigit():
                    self.w('$script:__st = %d' % (int(t) & 255))
                else:
                    self.w("$script:__st = __statusarg %s 'return'" % self.wargs(args[:1]))
            self.w('return')
            return False
        if name == 'exit':
            t = self._lit(args[0]) if args else None
            if not args:
                self.w('throw $script:__EX')
            elif t is not None and t.isdigit():
                self.w('$script:__st = %d' % (int(t) & 255))
                self.w('throw $script:__EX')
            else:
                self.w('__b_exit %s' % self.wargs(args[:1]))
            return False
        if name in (':', 'true', 'false'):
            if any(self._lit(a) is None for a in args):
                self.w('$null = %s' % self.wargs(args))
            self.w('$script:__st = %d' % (1 if name == 'false' else 0))
            return True
        if name == 'echo':
            for a in args:
                t = self._lit(a)
                if t is None or not re.match(r'-[neE]+\Z', t):
                    break
                if 'e' in t:
                    self.bad('echo-opt', 'echo %s (escape processing)' % t)
            self.w('__b_echo %s' % self.wargs(args))
            return True
        if name in ('test', '['):
            for a in args:
                t = self._lit(a)
                if t is not None and len(t) > 1 and t[0] == '-' and t[1:].isalpha() \
                        and t not in _TEST_OPS:
                    self.bad('test-op', 'test operator %s' % t)
            self.w('__b_test %s %s' % (self.wargs(args), '$true' if name == '[' else '$false'))
            return True
        if name == 'cd':
            t = self._lit(args[0]) if args else None
            if t is not None and len(t) > 1 and t[0] == '-':
                self.bad('builtin', 'cd %s (options are not supported)' % t)
            self.w('__b_cd %s' % self.wargs(args))
            return True
        if name == 'pwd':
            self.w('__b_pwd')
            return True
        if name == 'shift':
            self.w('__b_shift %s' % self.wargs(args))
            return True
        if name == 'unset':
            if any(self._lit(a) == '-f' for a in args):
                self.bad('builtin', 'unset -f')
            self.w('__b_unset %s' % self.wargs(args))
            return True
        if name in ('export', 'local'):
            return self.c_declare(name, args)
        if name == 'set':
            return self.c_set(args)
        if name in self.shell_builtins:
            self.bad('builtin', 'shell builtin `%s`' % name)
            return True
        if name in self.unix_tools and self.tools != 'external':
            self.bad('unix-tool', 'Unix command `%s` (does not exist on plain Windows)' % name)
            return True
        self.w('__ext %s' % self.wargs(words))
        return True

    def c_loopctl(self, name, args):
        depth = 1
        if args:
            t = self._lit(args[0])
            if len(args) > 1 or t is None or not t.isdigit() or int(t) < 1:
                self.bad('loop-control', '`%s` with a computed or invalid level' % name)
            else:
                depth = int(t)
        if not self.loops:
            self.bad('loop-control', '`%s` outside of a loop in the same function' % name)
            return False
        label, stvar = self.loops[-min(depth, len(self.loops))]
        self.w('%s = 0' % stvar)
        self.w('%s %s' % (name, label))
        return False

    def c_declare(self, name, args):
        if name == 'local' and self.func_depth == 0:
            self.bad('local', '`local` outside of a function body')
        for a in args:
            asg = a.assign
            t = self._lit(a)
            if asg is not None and asg[1] is None and not asg[2] and type(asg[3]) is not ArrayLit:
                value = self.wstr(asg[3], 'assign')
                if name == 'local':
                    self.w('__localv %s %s' % (sq(asg[0]), value))
                else:
                    self.w('__set %s %s' % (sq(asg[0]), value))
                    self.w('__export %s' % sq(asg[0]))
            elif t is not None and _IDENT.match(t):
                self.w('__%s %s' % (name, sq(t)))
            else:
                self.bad('builtin', '`%s` with options, arrays, += or computed names' % name)
        self.w('$script:__st = 0')
        return True

    def c_set(self, args):
        lits = [self._lit(a) for a in args]
        if not args:
            self.bad('set-opt', '`set` without arguments')
        i = 0
        while i < len(args):
            t = lits[i]
            if t == '--':
                self.w('$script:__P = %s' % self.wargs(args[i + 1:]))
                break
            if t is None or not re.match(r'[-+][A-Za-z]+\Z', t):
                self.bad('set-opt', 'set %s' % (t if t is not None else '<computed>'))
                break
            flag = '$true' if t[0] == '-' else '$false'
            for ch in t[1:]:
                if ch == 'e':
                    self.use_e = True
                    self.w('$script:__e = %s' % flag)
                elif ch == 'u':
                    self.use_u = True
                    self.w('$script:__u = %s' % flag)
                elif ch == 'o':
                    i += 1
                    opt = lits[i] if i < len(args) else None
                    if opt == 'errexit':
                        self.use_e = True
                        self.w('$script:__e = %s' % flag)
                    elif opt == 'nounset':
                        self.use_u = True
                        self.w('$script:__u = %s' % flag)
                    elif opt != 'pipefail':     # パイプラインはサブセット外なので pipefail は無作用
                        self.bad('set-opt', 'set -o %s' % (opt if opt is not None else '<computed>'))
                else:
                    self.bad('set-opt', 'set %s%s' % (t[0], ch))
            i += 1
        self.w('$script:__st = 0')
        return True

    # ---- 複合コマンド
    def n_if(self, n):
        def emit(i):
            c, b = n.clauses[i]
            k = self.cd_enter()
            self.node(c)
            self.cd_leave(k)
            self.w('if ($script:__st -eq 0) {')
            self.ind += 1
            self.node(b)
            self.ind -= 1
            self.w('} else {')
            self.ind += 1
            if i + 1 < len(n.clauses):
                emit(i + 1)
            elif n.else_body is not None:
                self.node(n.else_body)
            else:
                self.w('$script:__st = 0')
            self.ind -= 1
            self.w('}')
        self.wrap(self.rspec(n.redirs), lambda: emit(0))

    def _loop(self, redirs, head, before, body, cond=None):
        """ループの共通形。終了ステータスは「最後に実行した本体のステータス(無ければ 0)」。"""
        def emit():
            lv = self.new('l')
            label = 'L%d' % self.tmp
            self.w('%s = 0' % lv)
            dv = None
            if self.use_e and not self.in_cs:
                dv = self.new('d')
                self.w('%s = $script:__cd' % dv)
            self.w(':%s %s {' % (label, head(lv)))
            self.ind += 1
            if dv:
                self.w('$script:__cd = %s' % dv)
            if cond is not None:
                cond()
            if before:
                self.w(before(lv))
            self.loops.append((label, lv))
            self.node(body)
            self.loops.pop()
            self.w('%s = $script:__st' % lv)
            self.ind -= 1
            self.w('}')
            if dv:
                self.w('$script:__cd = %s' % dv)
            self.w('$script:__st = %s' % lv)
        self.wrap(self.rspec(redirs), emit)

    def n_while(self, n):
        def cond():
            k = self.cd_enter()
            self.node(n.cond)
            self.cd_leave(k)
            self.w('if ($script:__st -%s 0) { break }' % ('eq' if n.until else 'ne'))
        self._loop(n.redirs, lambda lv: 'while ($true)', None, n.body, cond)

    def n_for(self, n):
        items = '$__P' if n.words is None else self.wargs(n.words)
        iv = self.new('i')
        self._loop(n.redirs, lambda lv: 'foreach (%s in %s)' % (iv, items),
                   lambda lv: '__set %s %s' % (sq(n.var), iv), n.body)

    def _arith_opt(self, w):
        if w is None or not ''.join(p.text if type(p) is Lit else 'x' for p in w.parts).strip():
            return None
        return self.arith(w)

    def n_cfor(self, n):
        init = self._arith_opt(n.init)
        cond = self._arith_opt(n.cond)
        step = self._arith_opt(n.step)
        if init is not None:
            self.w('$null = %s' % init)
        head = 'for (; %s; %s)' % ('(%s -ne 0)' % cond if cond is not None else '$true',
                                    '$null = %s' % step if step is not None else '')
        self._loop(n.redirs, lambda lv: head, None, n.body)

    def n_case(self, n):
        def emit():
            v = self.new('c')
            self.w('%s = %s' % (v, self.wstr(n.word, 'case')))
            first = True
            for pats, body, term in n.items:
                if term != ';;':
                    self.bad('case-fallthrough', 'case terminator %s' % term)
                conds = ' -or '.join('(__m %s %s)' % (v, self.wpat(p)) for p in pats)
                self.w(('if (%s) {' if first else '} elseif (%s) {') % conds)
                first = False
                self.ind += 1
                if body is None or not getattr(body, 'items', True):
                    self.w('$script:__st = 0')
                else:
                    self.node(body)
                self.ind -= 1
            if first:
                self.w('$script:__st = 0')
            else:
                self.w('} else {')
                self.w('    $script:__st = 0')
                self.w('}')
        self.wrap(self.rspec(n.redirs), emit)

    def n_group(self, n):
        self.wrap(self.rspec(n.redirs), lambda: self.node(n.body))

    def n_subshell(self, n):
        self.node(n.body)
        self.bad('subshell', 'subshell ( ... )')

    def n_funcdef(self, n):
        self.line = n.line
        self.funcs.add(n.name)
        self.comment(n.line)
        self.w('$__F[%s] = {' % self.lit(n.name))
        self.ind += 1
        self.w('param([string[]]$__argv)')
        self.w('__enter $__argv')
        self.w('try {')
        self.ind += 1
        saved = self.loops
        self.loops = []
        self.func_depth += 1
        self.node(n.body)
        self.func_depth -= 1
        self.loops = saved
        self.ind -= 1
        self.w('} finally { __leave }')
        self.ind -= 1
        self.w('}')
        self.w('$script:__st = 0')

    def n_cond(self, n):
        self.line = n.line
        self.comment(n.line)
        self.wrap(self.rspec(n.redirs),
                  lambda: self.w('$script:__st = [int](-not %s)' % self.cond(n.expr)))
        self.ck()

    def n_arithcmd(self, n):
        self.line = n.line
        self.comment(n.line)
        self.wrap(self.rspec(n.redirs),
                  lambda: self.w('$script:__st = [int](%s -eq 0)' % self.arith(n.word)))
        self.ck()

    _handlers = {List: n_list, AndOr: n_andor, Pipeline: n_pipeline, Simple: n_simple, If: n_if,
                 While: n_while, For: n_for, CFor: n_cfor, Case: n_case, Group: n_group,
                 Subshell: n_subshell, FuncDef: n_funcdef, Cond: n_cond, ArithCmd: n_arithcmd}


def runtime_text():
    """埋め込むランタイム(ps_runtime.ps1)を返す。zipapp の中からも読める。"""
    import pkgutil
    data = pkgutil.get_data(__name__.rpartition('.')[0] or 'bashwin', 'ps_runtime.ps1')
    return data.decode('ascii').replace('\r\n', '\n')


def transpile(src, name='script.sh', tools='block'):
    """(PowerShell のテキスト|None, 問題のリスト, 構文エラー|None) を返す。

    問題が 1 件でもあればテキストは None(変換しない)。
    """
    from .interp import VERSION
    try:
        tree = parse(src)
    except ParseError as e:
        return None, [], 'line %d: %s' % (e.line, e.msg)
    em = Emitter(src, tools)
    body = em.run(tree)
    if em.problems:
        return None, em.problems, None
    out = ['%s %s (--ps1) from %s' % (MARKER, VERSION, _ascii(name)),
           '# DO NOT EDIT: change the bash script and generate this file again.',
           '# Needs Windows PowerShell 5.1 or later; no Python, no bash at run time.',
           '# Run it as its own process:  powershell -NoProfile -File <this file> [arguments]',
           '# Standard output is written as raw bytes (UTF-8) and does not go through the',
           '# PowerShell pipeline.',
           '',
           runtime_text().rstrip('\n'),
           '',
           '# ---- translated from %s ----' % _ascii(name),
           'try {']
    out.extend(body)
    out += ['} catch {',
            '    if (-not (__isx $_)) { __crash $_ }',
            '} finally {',
            '    __cleanup',
            '}',
            'exit $script:__st',
            '']
    return '\n'.join(out), [], None


def check(src, tools='block'):
    """(問題のリスト, 構文エラー|None)。問題が空なら変換できる。"""
    text, problems, err = transpile(src, tools=tools)
    return problems, err


def _read(path):
    import sys
    try:
        with open(path, 'rb') as f:
            return f.read().decode('utf-8', 'surrogateescape')
    except (OSError, TypeError) as e:
        sys.stderr.write('bashwin: %s: %s\n' % (path, getattr(e, 'strerror', None) or e))
        return None


def _report(path, problems):
    import sys
    seen = []
    for item in problems:
        if item not in seen:
            seen.append(item)
            sys.stdout.write('%s:%d: [%s] %s\n' % ((path,) + item))
    cats = sorted(set(p[1] for p in problems))
    sys.stdout.write('%s: NOT transpilable (%d blocking constructs: %s)\n' % (
        path, len(seen), ', '.join(cats)))


def check_file(path, tools='block'):
    """--ps1-check: 0=変換できる / 1=できない / 2=読めない・構文エラー"""
    import sys
    src = _read(path)
    if src is None:
        return 2
    problems, err = check(src, tools)
    if err:
        sys.stderr.write('%s: %s\n' % (path, err))
        return 2
    if problems:
        _report(path, problems)
        return 1
    sys.stdout.write('%s: within the PowerShell-transpilable subset\n' % path)
    return 0


def transpile_file(path, out=None, tools='block', force=False):
    """--ps1: 変換して .ps1 を書く。0=成功 / 1=変換できない / 2=エラー"""
    import os
    import sys
    src = _read(path)
    if src is None:
        return 2
    text, problems, err = transpile(src, os.path.basename(path), tools)
    if err:
        sys.stderr.write('%s: %s\n' % (path, err))
        return 2
    if problems:
        _report(path, problems)
        sys.stderr.write('bashwin: nothing was written (fail-closed)\n')
        return 1
    data = text.encode('ascii')
    if out == '-':
        getattr(sys.stdout, 'buffer', sys.stdout).write(data)
        return 0
    if out is None:
        out = os.path.splitext(path)[0] + '.ps1'
    if os.path.exists(out) and not force:
        try:
            with open(out, 'rb') as f:
                head = f.read(len(MARKER))
        except OSError:
            head = b''
        if head != MARKER.encode('ascii'):
            sys.stderr.write('bashwin: %s exists and was not generated by bashwin; not overwritten '
                             '(use --ps1-force)\n' % out)
            return 2
    with open(out, 'wb') as f:
        f.write(data)
    sys.stdout.write('%s -> %s\n' % (path, out))
    return 0
